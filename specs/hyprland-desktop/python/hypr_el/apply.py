"""Generate all component configs from the settings and reload the running session.

Everything is written to ~/.config/hypr-el/ (plus hyprtoolkit.conf, which has
no other lookup path). User-owned files in ~/.config/{hypr,waybar,mako,kitty}
are never touched; if they exist they take precedence (see hypr-el-session).
"""
