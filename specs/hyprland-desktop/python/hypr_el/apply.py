# --------------------------------------------------------------------------- desktop integration
def gtk_settings(t):
    if not shutil.which("gsettings"):
        return
    gs = lambda *a: _run(["gsettings", "set", *a])
    gs("org.gnome.desktop.interface", "color-scheme", "prefer-dark" if t["dark"] else "default")
    gs("org.gnome.desktop.interface", "gtk-theme", "Adwaita-dark" if t["dark"] else "Adwaita")
    # hyprland-desktop 1.x emptied the button layout; that also hid the close
    # button in GNOME sessions. Restore the GNOME default.
    cur = _run(["gsettings", "get", "org.gnome.desktop.wm.preferences", "button-layout"]).strip()
    if cur in ("':'", "':'\n"):
        _run(["gsettings", "reset", "org.gnome.desktop.wm.preferences", "button-layout"])


def _managed(path):
    try:
        with open(path) as f:
            return MARK in f.read(400)
    except OSError:
        return True   # does not exist


# --------------------------------------------------------------------------- main entry
def apply(reload=True, only_files=False):
    s = S.load()
    t = S.theme(s)
    d = S.CFG_DIR
    wp = wallpaper_path(s, t)

    _write(os.path.join(d, "settings.lua"), gen_lua(s, t, wp))
    _write(os.path.join(d, "waybar", "config.jsonc"), gen_waybar(s, t))
    _write(os.path.join(d, "waybar", "style.css"), gen_waybar_css(s, t))
    _write(os.path.join(d, "mako.conf"), gen_mako(s, t))
    _write(os.path.join(d, "kitty.conf"), gen_kitty(s, t))
    _write(os.path.join(d, "hyprpaper.conf"), gen_hyprpaper(wp))
    _write(os.path.join(d, "hyprlock.conf"), gen_hyprlock(s, t, wp))
    _write(os.path.join(d, "hypridle.conf"), gen_hypridle(s))
    tk = os.path.join(S.CONFIG_HOME, "hypr", "hyprtoolkit.conf")
    if _managed(tk):
        _write(tk, gen_hyprtoolkit(t))
    if only_files:
        return
    gtk_settings(t)
    if reload and in_hyprland():
        reload_session()


def _exec(cmd):
    _run(["hyprctl", "dispatch", f"hl.dsp.exec_cmd({json.dumps(cmd)})"])


def reload_session():
    _run(["hyprctl", "reload"])
    sess = shutil.which("hypr-el-session") or "/usr/bin/hypr-el-session"
    _run([sess, "restart"])
