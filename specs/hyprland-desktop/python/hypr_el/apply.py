# --------------------------------------------------------------------------- helpers
def _rgba(hexcol, alpha):
    h = hexcol.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha})"


def _hypr(hexcol, alpha=1.0):
    return "rgba(" + hexcol.lstrip("#") + f"{round(alpha * 255):02x})"


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def _run(cmd, **kw):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=10, **kw).stdout
    except (OSError, subprocess.SubprocessError):
        return ""


def in_hyprland():
    return bool(os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")) and shutil.which("hyprctl")


def _lua(v, ind=""):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        return "{ " + ", ".join(_lua(x, ind) for x in v) + " }"
    if isinstance(v, dict):
        inner = ind + "    "
        items = []
        for k, x in v.items():
            key = k if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) else "[" + json.dumps(k) + "]"
            items.append(f"{inner}{key} = {_lua(x, inner)},")
        return "{\n" + "\n".join(items) + "\n" + ind + "}"
    return "nil"


# --------------------------------------------------------------------------- detection
def detect_keyboard():
    out = _run(["gsettings", "get", "org.gnome.desktop.input-sources", "sources"])
    layouts, variants = [], []
    for src in re.findall(r"\('xkb',\s*'([^']+)'\)", out):
        l, _, v = src.partition("+")
        layouts.append(l)
        variants.append(v)
    if layouts:
        return layouts, variants
    out = _run(["localectl", "status"])
    m = re.search(r"X11 Layout:\s*([\w,-]+)", out)
    if m and m.group(1) != "n":
        v = re.search(r"X11 Variant:\s*([\w,-]+)", out)
        vs = v.group(1).split(",") if v and v.group(1) != "n" else []
        ls = m.group(1).split(",")
        return ls, (vs + [""] * len(ls))[: len(ls)]
    try:
        km = re.search(r'KEYMAP="?([\w-]+)', open("/etc/vconsole.conf").read())
        if km:
            return [re.match(r"[a-z]+", km.group(1)).group(0)], [""]
    except OSError:
        pass
    return ["us"], [""]


def monitors():
    if not in_hyprland():
        return []
    try:
        return json.loads(_run(["hyprctl", "-j", "monitors", "all"]) or "[]")
    except ValueError:
        return []


def wallpaper_path(s, t):
    if s.get("wallpaper") and os.path.exists(os.path.expanduser(s["wallpaper"])):
        return os.path.expanduser(s["wallpaper"])
    w, h = 3840, 2160
    mons = monitors()
    if mons:
        w = max(m.get("width", 0) for m in mons) or w
        h = max(m.get("height", 0) for m in mons) or h
    try:
        return wallpapers.render(t, w, h, S.WALLPAPER_CACHE)
    except (OSError, subprocess.SubprocessError):
        return "/usr/share/backgrounds/hypr-el/hypr-el-default.png"


# --------------------------------------------------------------------------- generators
def gen_lua(s, t, wp):
    layouts, variants = (s["kb_layouts"], s["kb_variants"]) if s["kb_layouts"] else detect_keyboard()
    variants = (list(variants) + [""] * len(layouts))[: len(layouts)]
    data = {k: v for k, v in s.items() if k not in ("monitors", "kb_layouts", "kb_variants", "theme")}
    data["theme"] = {k: v for k, v in t.items() if isinstance(v, (str, bool))}
    data["kb_layout"] = ",".join(layouts)
    data["kb_variant"] = ",".join(variants)
    data["monitors"] = [
        {"output": name, "mode": m.get("mode", "preferred"), "scale": m.get("scale", "auto"),
         "position": m.get("position", "auto")}
        for name, m in sorted(s["monitors"].items())
    ]
    data["wallpaper_path"] = wp
    return f"-- {MARK}\n-- edit with hypr-el-settings or ~/.config/hypr-el/settings.json\nreturn " + _lua(data) + "\n"


